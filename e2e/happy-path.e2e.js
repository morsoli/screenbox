import { existsSync, readFileSync, statSync } from 'node:fs'
import { browser, $, expect } from '@wdio/globals'

describe('local export happy path', () => {
  it('opens a synthetic recording, edits it, and creates all local export files', async () => {
    await browser.saveScreenshot('.cache/e2e-home.png')
    await $('details.settings-menu > summary').click()
    await $('[data-testid="language-zh-CN"]').click()
    await expect($('.card-top h2')).toHaveText('选择录制内容')
    await $('[data-testid="language-en"]').click()
    await expect($('.card-top h2')).toHaveText('Choose what to record')
    await $('[data-testid="theme-dark"]').click()
    await browser.waitUntil(async () => browser.execute(() => document.documentElement.dataset.theme === 'dark'))
    await browser.saveScreenshot('.cache/e2e-dark-home.png')
    await $('[data-testid="theme-system"]').click()
    await browser.waitUntil(async () => browser.execute(() => ['light', 'dark'].includes(document.documentElement.dataset.theme)))
    await $('[data-testid="theme-light"]').click()
    await browser.waitUntil(async () => browser.execute(() => document.documentElement.dataset.theme === 'light'))
    await browser.refresh()
    await expect($('.card-top h2')).toHaveText('Choose what to record')
    await browser.waitUntil(async () => browser.execute(() => document.documentElement.dataset.theme === 'light'))
    await $('details.settings-menu > summary').click()
    if (await $('[data-testid="language-en"]').getAttribute('aria-pressed') !== 'true') throw new Error('Language preference did not persist across reload')
    await $('[data-testid="language-zh-CN"]').click()
    await $('details.settings-menu > summary').click()
    const fixture = await browser.execute(async () => window.__TAURI__.core.invoke('create_fixture_project'))
    await browser.refresh()
    const row = await $('.project-item')
    await row.waitForDisplayed()
    await row.click()
    await expect($('h1')).toHaveText('E2E sample')
    const posterLoaded = await browser.execute(async () => {
      const image = new Image()
      image.src = document.querySelector('video').poster
      await image.decode()
      return image.naturalWidth > 0
    })
    if (!posterLoaded) throw new Error('Project preview poster did not load')
    await browser.saveScreenshot('.cache/e2e-editor.png')
    await $('details.settings-menu > summary').click()
    if (await $('[data-testid="language-zh-CN"]').getAttribute('aria-pressed') !== 'true') throw new Error('Language preference did not persist')
    await $('details.settings-menu > summary').click()
    const start = await $('.trim-inputs label:first-child input')
    await start.setValue('0.5')
    await $('.add-button').click()
    await $('.callout-line input').setValue('Focus here')
    await $('.controls-actions .secondary-button').click()
    await expect($('.message.success')).toBeDisplayed()
    await $('.editor-intro .primary-button').click()
    await $('.export-result').waitForDisplayed({ timeout: 120000 })
    const projects = await browser.execute(async () => window.__TAURI__.core.invoke('list_projects'))
    const exported = projects.find(item => item.id === fixture.id)
    const video = exported.lastExportPath
    for (const path of [video, video.replace(/\.(mp4|webm)$/, '.poster.jpg'), video.replace(/\.(mp4|webm)$/, '.transcript.md'), video.replace(/\.(mp4|webm)$/, '.summary.md')]) {
      if (!existsSync(path) || statSync(path).size === 0) throw new Error(`Missing export artifact: ${path}`)
    }
    const summary = readFileSync(video.replace(/\.(mp4|webm)$/, '.summary.md'), 'utf8')
    const transcript = readFileSync(video.replace(/\.(mp4|webm)$/, '.transcript.md'), 'utf8')
    if (!summary.includes('# 摘要：E2E sample') || !summary.includes('Focus here') || !transcript.startsWith('# 转录：')) throw new Error('Chinese sidecars do not match the selected language and recording edits')
    await $('details.settings-menu > summary').click()
    await $('[data-testid="language-en"]').click()
    await $('details.settings-menu > summary').click()
    await $('.preset-row button:last-child').click()
    await $('.controls-actions .primary-button').click()
    await browser.waitUntil(async () => {
      const updated = await browser.execute(async () => window.__TAURI__.core.invoke('list_projects'))
      return updated.find(item => item.id === fixture.id)?.lastExportPath?.endsWith('.webm')
    }, { timeout: 120000 })
    const webmProjects = await browser.execute(async () => window.__TAURI__.core.invoke('list_projects'))
    const webm = webmProjects.find(item => item.id === fixture.id).lastExportPath
    if (!existsSync(webm) || statSync(webm).size === 0) throw new Error('WebM preset did not export')
    const englishSummary = readFileSync(webm.replace(/\.(mp4|webm)$/, '.summary.md'), 'utf8')
    if (!englishSummary.startsWith('# Summary:')) throw new Error('English sidecar headings do not match the selected language')
  })
})
